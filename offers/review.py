"""D6 - Sales Team review card (Epic D: Offers).

Builds the card the Sales Team reads before deciding (D7): offer details, evidence,
forecast, risk numbers, version and hash.

Rule from the task table: figures come from STORED data, not AI text.
So the card holds only values read from the offer itself and from the stores
(prices, evidence, forecast, product rules), plus numbers computed from them
with Decimal. There is no free text and nothing generated by a model.

A card is only built for a DRAFT offer that passes validation (D3) and all
guardrails (D4/D5), and has both stored evidence and a stored forecast.
Anything else raises ReviewNotAllowed with the reasons (fail closed).
"""
from __future__ import annotations

from dataclasses import dataclass, field
from datetime import date, datetime, timezone
from decimal import Decimal
from typing import Any, Optional, Protocol

from offers.guardrails import (
    ActiveOffers,
    GuardrailConfig,
    PriceReader,
    ProductRules,
    _price_units,
    check_all_guardrails,
)
from offers.schema import Offer, OfferStatus
from offers.validation import CatalogReader, ValidationConfig, validate_offer

TWO_PLACES = Decimal("0.01")


class ReviewNotAllowed(ValueError):
    """The offer cannot go to Sales review. `reasons` says why."""

    def __init__(self, reasons) -> None:
        self.reasons = tuple(reasons)
        super().__init__("; ".join(self.reasons))


@dataclass(frozen=True)
class Evidence:
    """Stored evidence behind a candidate (a stock signal, H1). Facts are shown as stored."""

    ref: str
    kind: str
    facts: dict[str, Any] = field(default_factory=dict)


@dataclass(frozen=True)
class Forecast:
    """Stored numeric demand forecast (E5: 'offers can read a forecast number')."""

    ref: str
    expected_units: Decimal
    generated_at: datetime


class EvidenceReader(Protocol):
    def get_evidence(self, ref: str) -> Optional[Evidence]: ...


class ForecastReader(Protocol):
    def get_forecast(self, ref: str) -> Optional[Forecast]: ...


@dataclass
class InMemoryEvidence:
    data: dict[str, Evidence] = field(default_factory=dict)

    def get_evidence(self, ref: str) -> Optional[Evidence]:
        return self.data.get(ref)


@dataclass
class InMemoryForecasts:
    data: dict[str, Forecast] = field(default_factory=dict)

    def get_forecast(self, ref: str) -> Optional[Forecast]:
        return self.data.get(ref)


@dataclass(frozen=True)
class ReviewCard:
    offer_id: str
    version: int
    content_hash: str
    status: str
    generated_at: datetime
    details: dict[str, Any]
    evidence: dict[str, Any]
    forecast: dict[str, Any]
    lines: list[dict[str, Any]]
    flags: dict[str, Any]

    def to_dict(self) -> dict[str, Any]:
        """JSON-safe form for the UI: Decimals become strings, datetimes ISO strings."""
        return _jsonable(
            {
                "offer_id": self.offer_id,
                "version": self.version,
                "content_hash": self.content_hash,
                "status": self.status,
                "generated_at": self.generated_at,
                "details": self.details,
                "evidence": self.evidence,
                "forecast": self.forecast,
                "lines": self.lines,
                "flags": self.flags,
            }
        )

    def render_text(self) -> str:
        """Plain-text view. Labels and stored values only."""
        d = self.to_dict()
        out = [
            f"Offer {d['offer_id']}  version {d['version']}  hash {d['content_hash'][:12]}",
            f"Type: {d['details']['type']}  Branch: {d['details']['branch_id']}",
            f"Dates: {d['details']['start_date']} -> {d['details']['end_date']}",
            f"Quantity cap: {d['details']['quantity_cap']}",
        ]
        for k, v in d["details"]["terms"].items():
            out.append(f"{k}: {v}")
        out.append(f"Evidence {d['evidence']['ref']} ({d['evidence']['kind']}): {d['evidence']['facts']}")
        out.append(f"Forecast {d['forecast']['ref']}: {d['forecast']['expected_units']} units")
        for line in d["lines"]:
            out.append(
                f"{line['label']}: list {line['list_price']}, offer {line['offer_price']}, "
                f"cost {line['cost']}, discount {line['discount_percent']}%, margin {line['margin_percent']}%"
            )
        for k, v in d["flags"].items():
            out.append(f"{k}: {v}")
        return "\n".join(out)


def _jsonable(value: Any) -> Any:
    if isinstance(value, Decimal):
        return format(value, "f")
    if isinstance(value, (datetime, date)):
        return value.isoformat()
    if isinstance(value, dict):
        return {k: _jsonable(v) for k, v in value.items()}
    if isinstance(value, (list, tuple)):
        return [_jsonable(v) for v in value]
    return value


def _pct(numerator: Decimal, denominator: Decimal) -> Decimal:
    return (numerator / denominator * Decimal(100)).quantize(TWO_PLACES)


def _terms(offer: Offer) -> dict[str, Any]:
    """Only the fields that belong to this offer's type."""
    if offer.type.value == "discount":
        return {"discount_percent": offer.discount_percent}
    if offer.type.value == "buy2get1":
        return {"buy_qty": offer.buy_qty, "get_qty": offer.get_qty}
    return {
        "bundle_items": [
            {"product_id": i.product_id, "quantity": i.quantity} for i in offer.bundle_items
        ],
        "bundle_price": offer.bundle_price,
    }


def build_review_card(
    offer: Offer,
    *,
    catalog: CatalogReader,
    prices: PriceReader,
    rules: ProductRules,
    active: ActiveOffers,
    evidence_reader: EvidenceReader,
    forecast_reader: ForecastReader,
    validation_config: ValidationConfig,
    guardrail_config: GuardrailConfig,
    now: datetime | None = None,
) -> tuple[ReviewCard, Offer]:
    """Return (card, offer moved to PENDING_APPROVAL). Raises ReviewNotAllowed otherwise."""
    now = now or datetime.now(timezone.utc)
    reasons: list[str] = []

    if offer.status != OfferStatus.DRAFT:
        raise ReviewNotAllowed([f"only a draft can go to review, offer is {offer.status.value}"])

    reasons += validate_offer(offer, catalog, validation_config, now).reasons
    reasons += check_all_guardrails(offer, prices, rules, active, guardrail_config).reasons

    evidence = evidence_reader.get_evidence(offer.evidence_ref) if offer.evidence_ref else None
    if evidence is None:
        reasons.append(f"stored evidence not found: {offer.evidence_ref}")
    forecast = forecast_reader.get_forecast(offer.forecast_ref) if offer.forecast_ref else None
    if forecast is None:
        reasons.append(f"stored forecast not found: {offer.forecast_ref}")

    if reasons:
        raise ReviewNotAllowed(reasons)

    units, _ = _price_units(offer, prices)
    lines = [
        {
            "label": label,
            "list_price": list_price,
            "offer_price": offer_price.quantize(TWO_PLACES),
            "cost": cost,
            "discount_percent": _pct(list_price - offer_price, list_price),
            "margin_percent": _pct(offer_price - cost, offer_price),
        }
        for label, list_price, offer_price, cost, _floor in units
    ]

    expiries = [
        rules.earliest_expiry(offer.branch_id, pid)
        for pid in sorted(set(offer.product_ids) | {i.product_id for i in (offer.bundle_items or [])})
    ]
    expiries = [e for e in expiries if e is not None]
    days_before_expiry = min((e - offer.end_date).days for e in expiries) if expiries else None

    cap_ratio = (
        (Decimal(offer.quantity_cap) / forecast.expected_units).quantize(TWO_PLACES)
        if forecast.expected_units > 0
        else None
    )
    flags = {
        "quantity_cap_above_forecast": Decimal(offer.quantity_cap) > forecast.expected_units,
        "cap_to_forecast_ratio": cap_ratio,
        "days_between_offer_end_and_expiry": days_before_expiry,
    }

    pending = offer.model_copy(update={"status": OfferStatus.PENDING_APPROVAL})
    card = ReviewCard(
        offer_id=offer.offer_id,
        version=offer.version,
        content_hash=pending.content_hash(),
        status=pending.status.value,
        generated_at=now,
        details={
            "branch_id": offer.branch_id,
            "type": offer.type.value,
            "product_ids": list(offer.product_ids),
            "start_date": offer.start_date,
            "end_date": offer.end_date,
            "quantity_cap": offer.quantity_cap,
            "terms": _terms(offer),
        },
        evidence={"ref": evidence.ref, "kind": evidence.kind, "facts": dict(evidence.facts)},
        forecast={
            "ref": forecast.ref,
            "expected_units": forecast.expected_units,
            "generated_at": forecast.generated_at,
        },
        lines=lines,
        flags=flags,
    )
    return card, pending
